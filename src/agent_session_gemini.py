def version_is_pinned(reported: str) -> bool:
    return isinstance(reported, str) and reported.strip() == PINNED_CLI_VERSION


def is_new_session_request(session_id: Optional[str]) -> bool:
    if session_id is None:
        return True
    if not isinstance(session_id, str):
        return False
    value = session_id.strip().lower()
    return value in ("", "new") or value.startswith("new:")


def event_session_matches(event: Dict[str, Any], session_id: str) -> bool:
    return event.get("session_id") == session_id


def tool_name_is_permitted(name: Any) -> bool:
    return name in READ_ONLY_TOOLS


def model_is_honored(requested: Optional[str], reported: Any) -> bool:
    if not requested:
        return True
    return isinstance(reported, str) and reported == requested


def manifests_equal(before: Dict[str, Any], after: Dict[str, Any]) -> bool:
    return before == after


def digest_matches(expected: Optional[str], actual: Optional[str]) -> bool:
    return bool(expected) and expected == actual


