@dataclass
class _Run:
    run_id: str
    binding: RunBinding
    request_snapshot: str
    request_fingerprint: str
    idempotency_key: Optional[str]
    workspace: str
    native_session_id: str
    requested_model: Optional[str]
    run_dir: str
    state: str = RunState.QUEUED
    native_state: Optional[str] = None
    turns: List[NativeTurn] = field(default_factory=list)
    manifest_before_sha: Optional[str] = None
    process: Any = None
    collected: Optional[CollectedResult] = None
    recovered: bool = False


def _canon(value: Any) -> bytes:
    return json.dumps(value, sort_keys=True, ensure_ascii=False, separators=(",", ":")).encode("utf-8")


class GeminiCliAgentSessionAdapter(AgentSessionAdapter):
    """One application: the pinned Gemini CLI in headless stream-json mode."""

    app_kind = APP_KIND

    SUPPORTED = frozenset({"capabilities", "submit", "status", "collect"})
    UNSUPPORTED_REASONS = {
        "continue": "follow-up turns (--resume) are not verified for this bridge; later slice",
        "cancel": "process interruption is not part of this slice",
    }

    def __init__(self, config: GeminiCliConfig, *,
                 launcher: Optional[Callable[..., Any]] = None,
                 version_probe: Optional[Callable[[GeminiCliConfig], str]] = None,
                 instance_ids: Optional[Tuple[str, ...]] = None):
        self._config = config
        self._launcher = launcher or default_launcher
        self._version_probe = version_probe or default_version_probe
        self._instance_ids = frozenset(instance_ids or DEFAULT_INSTANCE_IDS)
        self._registry_path = os.path.join(config.evidence_root, "registry.jsonl")
        self._runs: Dict[str, _Run] = {}
        self._idem: Dict[str, Tuple[str, str]] = {}
        self._registry_problem: Optional[str] = None
        self._load_registry()

    # --- registry -----------------------------------------------------------
    def _persist(self, event: str, run: _Run, extra: Optional[Dict[str, Any]] = None) -> None:
        record: Dict[str, Any] = {
            "event": event, "run_id": run.run_id, "app_kind": run.binding.app_kind,
            "instance_id": run.binding.instance_id, "session_id": run.binding.session_id,
            "task_id": run.binding.task_id, "attempt": run.binding.attempt,
            "request_fingerprint": run.request_fingerprint,
            "request_snapshot": run.request_snapshot,
            "idempotency_key": run.idempotency_key, "workspace": run.workspace,
            "native_session_id": run.native_session_id, "requested_model": run.requested_model,
            "run_dir": run.run_dir, "state": run.state, "native_state": run.native_state,
            "at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        }
        if extra:
            record.update(extra)
        os.makedirs(os.path.dirname(self._registry_path), exist_ok=True)
        with open(self._registry_path, "ab") as fh:
            fh.write(_canon(record) + b"\n")
            fh.flush()
            os.fsync(fh.fileno())

    def _load_registry(self) -> None:
        if not os.path.exists(self._registry_path):
            return
        try:
            with open(self._registry_path, "rb") as fh:
                lines = fh.read().decode("utf-8").splitlines()
            records = [json.loads(line) for line in lines if line.strip()]
            for record in records:
                if not isinstance(record, dict) or not isinstance(record.get("run_id"), str):
                    raise ValueError("registry record without run_id")
        except (OSError, ValueError, UnicodeDecodeError) as exc:
            self._registry_problem = f"registry unreadable: {exc}"
            return
        for record in records:
            run = self._runs.get(record["run_id"])
            if run is None:
                run = _Run(run_id=record["run_id"],
                           binding=RunBinding(record.get("app_kind"), record.get("instance_id"),
                                              record.get("session_id"), record.get("task_id"),
                                              record.get("attempt")),
                           request_snapshot=record.get("request_snapshot") or "",
                           request_fingerprint=record.get("request_fingerprint") or "",
                           idempotency_key=record.get("idempotency_key"),
                           workspace=record.get("workspace") or "",
                           native_session_id=record.get("native_session_id") or "",
                           requested_model=record.get("requested_model"),
                           run_dir=record.get("run_dir") or "", recovered=True)
                self._runs[run.run_id] = run
            run.state = record.get("state") or run.state
            run.native_state = record.get("native_state") or run.native_state
            if record.get("event") == "collected":
                run.collected = CollectedResult(
                    run_id=run.run_id, declared_status=record.get("declared_status") or "unreported",
                    artifacts=record.get("artifacts") or [], usage=record.get("usage") or {},
                    raw_refs=record.get("raw_refs") or [],
                    unverified=(record.get("unverified") or []) + ["recovered registry record"])
            key = record.get("idempotency_key")
            if key:
                self._idem[key] = (run.request_fingerprint, run.run_id)
        # A run that was dispatched but never collected has no live process now:
        # its outcome is unknown and it is never re-dispatched.
        for run in self._runs.values():
            if run.collected is None and run.state in (RunState.QUEUED, RunState.RUNNING):
                run.state = RunState.UNKNOWN
                run.native_state = "outcome-unknown-after-reopen"

    # --- contract -----------------------------------------------------------
    def capabilities(self) -> Dict[str, Any]:
        out: Dict[str, Any] = {}
        for name in CAPABILITIES:
            if name in self.SUPPORTED:
                out[name] = {"supported": True, "detail": _SUPPORT_DETAIL[name]}
            else:
                out[name] = {"supported": False, "reason": self.UNSUPPORTED_REASONS[name]}
        out["host"] = {"cli_version": PINNED_CLI_VERSION, "tools": list(READ_ONLY_TOOLS),
                       "enforced_by": "admin-tier policy file + preflight refusal of workspace host config"}
        return out

    def _validate(self, request: SubmitRequest) -> None:
        session = request.session
        if session.app_kind != self.app_kind:
            raise UnsupportedAddress(f"adapter {self.app_kind!r} cannot dispatch to {session.app_kind!r}")
        if session.instance_id not in self._instance_ids:
            raise UnsupportedAddress(f"unsupported instance {session.instance_id!r}")
        if not is_new_session_request(session.session_id):
            raise UnsupportedAddress(
                f"session {session.session_id!r}: this slice only starts a NEW session")
        if request.budget_tokens is not None:
            raise UnsupportedRequest("a token budget cannot be enforced by this bridge; refusing")
        if request.allowed_scope:
            raise UnsupportedRequest(
                "path-level scope cannot be enforced; only the whole workspace read-only is supported")
        if not isinstance(request.instructions, str) or not request.instructions.strip():
            raise UnsupportedRequest("instructions must be non-empty text")

    def submit(self, request: SubmitRequest) -> RunStatus:
        self._require("submit")
        if self._registry_problem:
            raise RegistryUnavailable(f"refusing to dispatch: {self._registry_problem}")
        self._validate(request)
        fingerprint = request.fingerprint()
        key = request.idempotency_key
        if key and key in self._idem:
            stored, run_id = self._idem[key]
            if stored != fingerprint:
                raise IdempotencyConflict(key)
            run = self._runs[run_id]
            turn = run.turns[0] if run.turns else None
            return RunStatus(run_id=run_id, state=run.state, binding=run.binding,
                             native_turn=turn, latest_turn=turn, native_state=run.native_state,
                             note="idempotent replay; not re-dispatched")

        workspace = os.path.abspath(request.workspace) if isinstance(request.workspace, str) else request.workspace
        problems = workspace_preflight(workspace, self._config.evidence_root, self._config.cli_home)
        if problems:
            raise HostRestrictionUnavailable("; ".join(problems))
        reported = self._version_probe(self._config)
        if not version_is_pinned(reported):
            raise HostRestrictionUnavailable(
                f"CLI version {reported!r} is not the verified {PINNED_CLI_VERSION}")

        run_id = f"gemini-run-{uuid.uuid4().hex[:12]}"
        native_session_id = str(uuid.uuid4())
        run_dir = os.path.join(self._config.evidence_root, "runs", run_id)
        run = _Run(run_id=run_id, binding=RunBinding.of(request),
                   request_snapshot=request.snapshot(), request_fingerprint=fingerprint,
                   idempotency_key=key, workspace=workspace,
                   native_session_id=native_session_id,
                   requested_model=request.session.model_id, run_dir=run_dir,
                   state=RunState.QUEUED, native_state="reserved")
        try:
            os.makedirs(run_dir, exist_ok=False)
            policy_path = os.path.join(run_dir, "admin-policy.toml")
            write_bytes(policy_path, ADMIN_POLICY_TOML.encode("utf-8"))
            settings_dir = os.path.join(self._config.cli_home, ".gemini")
            os.makedirs(settings_dir, exist_ok=True)
            write_bytes(os.path.join(settings_dir, "settings.json"),
                        json.dumps(locked_settings(self._config), indent=2).encode("utf-8"))
            manifest = tree_manifest(workspace)
            manifest_bytes = _canon(manifest)
            write_bytes(os.path.join(run_dir, "workspace-before.json"), manifest_bytes)
            run.manifest_before_sha = hashlib.sha256(manifest_bytes).hexdigest()
            self._runs[run_id] = run
            if key:
                self._idem[key] = (fingerprint, run_id)
            # Registered BEFORE the external process exists.
            self._persist("reserved", run, {"manifest_before_sha256": run.manifest_before_sha,
                                            "cli_version": reported,
                                            "env_names": list(self._config.env_names)})
        except OSError as exc:
            self._runs.pop(run_id, None)
            if key:
                self._idem.pop(key, None)
            raise RegistryUnavailable(f"registry/evidence not writable; refusing to dispatch: {exc}") from None

        argv = build_argv(self._config, session_id=native_session_id, policy_path=policy_path,
                          model=request.session.model_id)
        stdin_bytes = ("JH task (read-only; cite sources as path:line):\n" + request.instructions).encode("utf-8")
        try:
            run.process = self._launcher(argv, cwd=workspace, env=build_env(self._config),
                                         stdin_bytes=stdin_bytes,
                                         stdout_path=os.path.join(run_dir, "stdout.jsonl"),
                                         stderr_path=os.path.join(run_dir, "stderr.txt"))
        except OSError as exc:
            run.state = RunState.FAILED
            run.native_state = "launch-failed"
            self._persist("dispatch_failed", run, {"error": str(exc)})
            raise RuntimeError(f"could not start Gemini CLI: {exc}") from None
        turn = NativeTurn(native_turn_id=f"{native_session_id}#invocation-1",
                          native_session_id=native_session_id, purpose="initial")
        run.turns = [turn]
        run.state = RunState.RUNNING
        run.native_state = "process-started"
        self._persist("dispatched", run, {"argv_tail": argv[len(self._config.argv_prefix):]})
        return RunStatus(run_id=run_id, state=run.state, binding=run.binding, native_turn=turn,
                         latest_turn=turn, native_state=run.native_state,
                         note="CLI started; native turn id is adapter-assigned (host exposes none)")

    def _resolve(self, session: SessionAddress, run_id: Optional[str]) -> Optional[_Run]:
        run = self._runs.get(run_id or "")
        if run is None:
            return None
        wanted = RunBinding(session.app_kind, session.instance_id, session.session_id,
                            run.binding.task_id, run.binding.attempt)
        if run.binding != wanted:
            raise AddressMismatch(run_id, run.binding, wanted)
        return run

    def status(self, session: SessionAddress, run_id: Optional[str]) -> RunStatus:
        self._require("status")
        run = self._resolve(session, run_id)
        if run is None:
            return RunStatus(run_id=run_id, state=RunState.UNKNOWN, note="no run with this id")
        if run.state == RunState.RUNNING and run.process is not None and run.process.poll() is not None:
            run.native_state = f"process-exited:{run.process.returncode}"
        latest = run.turns[-1] if run.turns else None
        return RunStatus(run_id=run.run_id, state=run.state, binding=run.binding,
                         native_turn=latest, latest_turn=latest, native_state=run.native_state)

    def collect(self, session: SessionAddress, run_id: Optional[str],
                timeout: float = 600.0) -> CollectedResult:
        self._require("collect")
        run = self._resolve(session, run_id)
        if run is None:
            return CollectedResult(run_id=run_id, declared_status="unreported",
                                   unverified=["collect: no run with this id"])
        if run.collected is not None:
            return run.collected
        if run.recovered or run.process is None:
            return CollectedResult(run_id=run.run_id, declared_status="unreported",
                                   raw_refs=[run.native_session_id],
                                   unverified=["no live process for this run; outcome unknown, not re-dispatched"])
        try:
            returncode = run.process.wait(timeout=timeout)
        except subprocess.TimeoutExpired:
            # Bounded wait. The run stays observable; nothing is re-sent.
            return CollectedResult(run_id=run.run_id, declared_status="unreported",
                                   raw_refs=[run.native_session_id],
                                   unverified=[f"process still running after {timeout}s bounded wait; "
                                               "not collected, not re-dispatched"])
        return self._finish(run, returncode)

    def _finish(self, run: _Run, returncode: Any) -> CollectedResult:
        unverified: List[str] = ["adapter observation only; independent review decides success"]
        evidence: Dict[str, Any] = {}
        for name in ("stdout.jsonl", "stderr.txt"):
            path = os.path.join(run.run_dir, name)
            if os.path.isfile(path):
                size, digest = sha256_file(path)
                evidence[name] = {"path": path, "bytes": size, "sha256": digest}
            else:
                evidence[name] = None
                unverified.append(f"evidence missing: {name}")
        stdout_bytes = b""
        if evidence.get("stdout.jsonl"):
            with open(evidence["stdout.jsonl"]["path"], "rb") as fh:
                stdout_bytes = fh.read()
            if not digest_matches(evidence["stdout.jsonl"]["sha256"], hashlib.sha256(stdout_bytes).hexdigest()):
                unverified.append("stdout evidence changed while being read")
        events, parse_problems = parse_stream(stdout_bytes)
        assoc = associate(events, run.native_session_id) if events else {
            "problems": ["no native events"], "init": None, "result": None, "tool_calls": [],
            "assistant_text": "", "errors": [], "denied_requests": []}
        problems = parse_problems + assoc["problems"]

        chat = find_chat_record(self._config.cli_home, run.native_session_id)
        if chat:
            with open(chat, "rb") as fh:
                chat_bytes = fh.read()
            copy_path = os.path.join(run.run_dir, "host-chat-record.jsonl")
            write_bytes(copy_path, chat_bytes)
            size, digest = sha256_file(copy_path)
            if not digest_matches(hashlib.sha256(chat_bytes).hexdigest(), digest):
                problems.append("host chat record copy does not match its source bytes")
            evidence["host-chat-record.jsonl"] = {"path": copy_path, "source": chat,
                                                  "bytes": size, "sha256": digest}
        else:
            evidence["host-chat-record.jsonl"] = None
            unverified.append("host chat record for this session not found")

        after = tree_manifest(run.workspace) if os.path.isdir(run.workspace) else {"missing": True}
        after_bytes = _canon(after)
        write_bytes(os.path.join(run.run_dir, "workspace-after.json"), after_bytes)
        before_path = os.path.join(run.run_dir, "workspace-before.json")
        with open(before_path, "rb") as fh:
            before_bytes = fh.read()
        before_ok = digest_matches(run.manifest_before_sha, hashlib.sha256(before_bytes).hexdigest())
        if not before_ok:
            problems.append("workspace-before manifest on disk does not match the registered digest")
        workspace_unchanged = before_ok and manifests_equal(json.loads(before_bytes.decode("utf-8")), after)
        if not workspace_unchanged:
            problems.append("workspace modified (or unprovable) during the run")

        init = assoc["init"] or {}
        reported_model = init.get("model")
        if not model_is_honored(run.requested_model, reported_model):
            problems.append(f"requested model {run.requested_model!r} not honored (host reports {reported_model!r})")
        result_event = assoc["result"] or {}
        usage, usage_missing = usage_from_result(assoc["result"])
        unverified += usage_missing
        unverified.append("native turn ids: not exposed by stream-json; turn count unknown")
        backend_models = sorted((usage.get("models") or {}).keys())

        host_status = result_event.get("status")
        clean = (not problems and returncode == 0 and host_status == "success"
                 and evidence.get("stdout.jsonl") is not None)
        if clean:
            run.state = RunState.DECLARED_COMPLETE
            declared = "success"
        else:
            run.state = RunState.FAILED
            declared = host_status if (host_status and not assoc["problems"]) else "unattributed"
            unverified += problems
        run.native_state = f"exit:{returncode};result:{host_status}"
        refs = extract_source_refs(assoc["assistant_text"], run.workspace)
        artifact = {
            "native_session_id": run.native_session_id,
            "requested_model": run.requested_model,
            "host_reported_model": reported_model,
            "backend_models": backend_models,
            "tool_calls": assoc["tool_calls"],
            "denied_tool_requests": assoc["denied_requests"],
            "host_errors": assoc["errors"],
            "assistant_text": assoc["assistant_text"],
            "source_refs": refs,
            "workspace_unchanged": workspace_unchanged,
            "exit_code": returncode,
        }
        if any(not r["verified"] for r in refs):
            unverified.append("some source references did not resolve in the workspace")
        if not refs:
            unverified.append("delivery carries no path:line source reference")
        result = CollectedResult(run_id=run.run_id, declared_status=declared, artifacts=[artifact],
                                 usage=usage, raw_refs=[run.native_session_id] +
                                 [e["path"] for e in evidence.values() if e],
                                 unverified=unverified)
        run.collected = result
        self._persist("collected", run, {"declared_status": declared, "artifacts": result.artifacts,
                                         "usage": usage, "raw_refs": result.raw_refs,
                                         "unverified": unverified, "evidence": evidence})
        return result

    def continue_run(self, session: SessionAddress, run_id: Optional[str],
                     instructions: str, idempotency_key: Optional[str] = None) -> RunStatus:
        raise UnsupportedCapability(self.app_kind, "continue", self.UNSUPPORTED_REASONS["continue"])

    def cancel(self, session: SessionAddress, run_id: Optional[str]) -> RunStatus:
        raise UnsupportedCapability(self.app_kind, "cancel", self.UNSUPPORTED_REASONS["cancel"])

    def inspect(self, run_id: str) -> Optional[_Run]:
        return self._runs.get(run_id)

    def _require(self, capability: str) -> None:
        if capability not in self.SUPPORTED:
            raise UnsupportedCapability(self.app_kind, capability,
                                        self.UNSUPPORTED_REASONS.get(capability, "not observed"))


def verify_run_evidence(registry_path: str, run_id: str) -> Dict[str, Any]:
    """Re-read the evidence files of a collected run and compare bytes on disk
    with the registered sizes and digests. Matching digests prove byte identity
    only, not provenance or completeness."""
    with open(registry_path, "rb") as fh:
        records = [json.loads(l) for l in fh.read().decode("utf-8").splitlines() if l.strip()]
    collected = [r for r in records if r.get("run_id") == run_id and r.get("event") == "collected"]
    if not collected:
        return {"ok": False, "reason": "no collected record"}
    report: Dict[str, Any] = {"ok": True, "files": {}}
    for name, meta in (collected[-1].get("evidence") or {}).items():
        if meta is None:
            report["files"][name] = "absent at collect"
            continue
        if not os.path.isfile(meta["path"]):
            report["ok"] = False
            report["files"][name] = "missing on disk"
            continue
        size, digest = sha256_file(meta["path"])
        same = size == meta["bytes"] and digest_matches(meta["sha256"], digest)
        report["files"][name] = "match" if same else "mismatch"
        report["ok"] = report["ok"] and same
    return report


