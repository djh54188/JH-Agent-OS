def parse_stream(data: bytes) -> Tuple[List[Dict[str, Any]], List[str]]:
    """Native JSONL -> events, plus problems (never repaired or skipped silently)."""
    events: List[Dict[str, Any]] = []
    problems: List[str] = []
    try:
        text = data.decode("utf-8")
    except UnicodeDecodeError as exc:
        return [], [f"stream is not UTF-8: {exc}"]
    for number, line in enumerate(text.splitlines(), start=1):
        if not line.strip():
            continue
        try:
            value = json.loads(line)
        except json.JSONDecodeError:
            problems.append(f"line {number}: not JSON")
            continue
        if not isinstance(value, dict) or value.get("type") not in NATIVE_EVENT_TYPES:
            problems.append(f"line {number}: not a native stream-json event")
            continue
        events.append(value)
    return events, problems


def associate(events: List[Dict[str, Any]], session_id: str) -> Dict[str, Any]:
    """Bind the native events to this run's session and pair tool calls."""
    out: Dict[str, Any] = {"problems": [], "init": None, "result": None, "tool_calls": [],
                           "assistant_text": "", "errors": [], "denied_requests": []}
    inits = [e for e in events if e["type"] == "init"]
    if len(inits) != 1:
        out["problems"].append(f"expected exactly one init event, saw {len(inits)}")
    if inits:
        out["init"] = inits[0]
        if not event_session_matches(inits[0], session_id):
            out["problems"].append(
                f"init session {inits[0].get('session_id')!r} != dispatched {session_id!r}")
    results = [e for e in events if e["type"] == "result"]
    if len(results) != 1:
        out["problems"].append(f"expected exactly one result event, saw {len(results)}")
    if results:
        out["result"] = results[-1]
        if events and events[-1] is not results[-1]:
            out["problems"].append("result event is not the last event")
    if events and events[0]["type"] != "init":
        out["problems"].append("first event is not init")
    calls: Dict[str, Dict[str, Any]] = {}
    order: List[str] = []
    texts: List[str] = []
    for event in events:
        kind = event["type"]
        if kind == "tool_use":
            tool_id = event.get("tool_id")
            if not isinstance(tool_id, str) or not tool_id:
                out["problems"].append("tool_use without tool_id")
                continue
            if tool_id in calls:
                out["problems"].append(f"duplicate tool_use id {tool_id!r}")
                continue
            calls[tool_id] = {"tool_id": tool_id, "tool_name": event.get("tool_name"),
                              "parameters": event.get("parameters"), "result": None}
            order.append(tool_id)
        elif kind == "tool_result":
            tool_id = event.get("tool_id")
            call = calls.get(tool_id)
            if call is None:
                out["problems"].append(f"tool_result {tool_id!r} has no preceding tool_use")
                continue
            if call["result"] is not None:
                out["problems"].append(f"tool_result {tool_id!r} reported twice")
                continue
            call["result"] = {"status": event.get("status"),
                              "output": event.get("output") if "output" in event else None,
                              "error": event.get("error")}
        elif kind == "message" and event.get("role") == "assistant":
            content = event.get("content")
            if isinstance(content, str):
                texts.append(content)
        elif kind == "error":
            out["errors"].append({"severity": event.get("severity"), "message": event.get("message")})
    for tool_id in order:
        call = calls[tool_id]
        if call["result"] is None:
            out["problems"].append(f"tool_use {tool_id!r} has no tool_result")
        if not tool_name_is_permitted(call["tool_name"]):
            # The host must have refused it. A success here is a breach.
            status = (call["result"] or {}).get("status")
            if status == "success":
                out["problems"].append(
                    f"non-read-only tool {call['tool_name']!r} reported success: host restriction breached")
            else:
                out["denied_requests"].append(call["tool_name"])
        out["tool_calls"].append(call)
    out["assistant_text"] = "".join(texts)
    return out


def extract_source_refs(text: str, workspace: str) -> List[Dict[str, Any]]:
    """`path:line[-line]` references in the delivery, checked against the tree.
    A reference that does not resolve inside the workspace stays unverified."""
    refs: List[Dict[str, Any]] = []
    seen = set()
    for match in _SOURCE_REF.finditer(text or ""):
        path, start, end = match.group(1), int(match.group(2)), match.group(3)
        key = (path, start, end)
        if key in seen:
            continue
        seen.add(key)
        ref: Dict[str, Any] = {"path": path, "line": start,
                               "end_line": int(end) if end else None, "verified": False}
        rel = path.replace("\\", "/")
        candidate = os.path.join(workspace, *rel.split("/"))
        if rel.startswith("/") or ".." in rel.split("/"):
            ref["reason"] = "not a workspace-relative path"
        elif not _within(candidate, workspace) or not os.path.isfile(candidate):
            ref["reason"] = "file not found in workspace"
        else:
            with open(candidate, "rb") as fh:
                lines = fh.read().count(b"\n") + 1
            last = ref["end_line"] or start
            if 1 <= start <= last <= lines:
                ref["verified"] = True
            else:
                ref["reason"] = f"line outside 1..{lines}"
        refs.append(ref)
    return refs


def find_chat_record(cli_home: str, session_id: str) -> Optional[str]:
    """The host's own session record for this session id, if it wrote one."""
    pattern = os.path.join(cli_home, ".gemini", "tmp", "*", "chats", "session-*.jsonl")
    for path in sorted(_glob.glob(pattern)):
        try:
            with open(path, "rb") as fh:
                first = fh.readline()
            if json.loads(first.decode("utf-8")).get("sessionId") == session_id:
                return path
        except (OSError, ValueError, UnicodeDecodeError):
            continue
    return None


def usage_from_result(result: Optional[Dict[str, Any]]) -> Tuple[Dict[str, Any], List[str]]:
    """Copy the host's stats; a missing field stays missing (never zero-filled)."""
    if not result or not isinstance(result.get("stats"), dict):
        return {}, ["usage unknown: result event carries no stats"]
    stats = result["stats"]
    usage: Dict[str, Any] = {}
    missing: List[str] = []
    for key in ("total_tokens", "input_tokens", "output_tokens", "cached", "tool_calls", "duration_ms"):
        if key in stats:
            usage[key] = stats[key]
        else:
            missing.append(f"usage field {key!r} not reported by host")
    if isinstance(stats.get("models"), dict):
        usage["models"] = stats["models"]
    usage["source"] = "stream-json result.stats (session cumulative for this invocation)"
    return usage, missing


