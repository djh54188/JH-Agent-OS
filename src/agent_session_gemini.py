"""Gemini CLI AgentSessionAdapter (Hark-派单-11, first non-Codex session bridge).

A THIN adapter: it drives an already-installed, version-pinned Gemini CLI in
headless mode (`-o stream-json`) for ONE first task, and observes what the host
itself produced. The tool loop (think -> tool -> result -> continue) is the
CLI's own; this module does not execute tools, does not run a model loop and is
not a runtime or scheduler.

What it relies on (pinned to Gemini CLI 0.65.0, see docs/gemini-cli-adapter.md):

* Native events: the CLI's StreamJsonFormatter writes one JSON object per line
  with `type` in {init, message, tool_use, tool_result, error, result}.
  `init` carries `session_id` and `model`; `tool_use` carries `tool_name`,
  `tool_id`, `parameters`; `tool_result` carries `tool_id`, `status`, optional
  `output`/`error`; `result` carries `status` and `stats`. No native turn id is
  emitted, so native turns are reported as unknown rather than invented.
* Session identity: `--session-id <uuid>` makes the host use a session id the
  adapter chose BEFORE launch, so the registry can name the native session even
  when the process outcome is unknown. The host's own chat record
  (`<cli_home>/.gemini/tmp/<project>/chats/session-*.jsonl`, first line
  `sessionId`) is collected as secondary evidence when present.
* Read-only enforcement is done by the HOST, not by prompt text: an admin-tier
  policy file (`--admin-policy`, highest tier) denies every tool and allows only
  read_file / grep_search / glob / list_directory. Denied tools are removed from
  the tool declarations the model sees; offline host probes showed that neither
  `--approval-mode yolo`, workspace policies/settings nor user policies widen
  that set. Workspace-level configuration that could start processes outside
  the tool path (MCP servers, hooks, discovery commands, `.env`) is refused at
  preflight instead of being trusted.
* A git worktree is NOT a sandbox. The adapter additionally snapshots the target
  tree before launch and compares it at collect; any change is reported.

Contract rules kept: `continue` and `cancel` are UNSUPPORTED. A dispatch is
registered before any external process starts; an unknown outcome is never
re-dispatched (also after the registry is reopened). `declared_complete` is the
host's claim, never task success.
"""
