@dataclass(frozen=True)
class GeminiCliConfig:
    """How to start the pinned CLI. No credential is stored here: `env_names`
    lists variable NAMES whose values pass through from this process."""

    argv_prefix: Tuple[str, ...]           # e.g. ("node", "/opt/gemini/bundle/gemini.js")
    cli_home: str                          # isolated GEMINI_CLI_HOME for this bridge
    evidence_root: str                     # registry + evidence, outside the workspace
    env_names: Tuple[str, ...] = ()        # e.g. ("GEMINI_API_KEY",) — names only
    extra_env: Tuple[Tuple[str, str], ...] = ()   # non-secret overrides (tests / offline probes)
    auth_type: Optional[str] = None        # host auth method name, e.g. "gemini-api-key" (not a secret)
    version_timeout: float = 30.0


def locked_settings(config: GeminiCliConfig) -> Dict[str, Any]:
    settings = json.loads(json.dumps(LOCKED_USER_SETTINGS))
    if config.auth_type:
        settings["security"] = {"auth": {"selectedType": config.auth_type}}
    return settings


def build_env(config: GeminiCliConfig) -> Dict[str, str]:
    env = {name: os.environ[name] for name in BASE_ENV_NAMES if name in os.environ}
    for name in config.env_names:
        if name in os.environ:
            env[name] = os.environ[name]
    env["GEMINI_CLI_HOME"] = config.cli_home
    env["HOME"] = config.cli_home
    env["USERPROFILE"] = config.cli_home
    env["GEMINI_CLI_NO_RELAUNCH"] = "true"
    env["NO_COLOR"] = "1"
    for name, value in config.extra_env:
        env[name] = value
    return env


def build_argv(config: GeminiCliConfig, *, session_id: str, policy_path: str,
               model: Optional[str]) -> List[str]:
    argv = list(config.argv_prefix) + [
        "-o", "stream-json",
        "--session-id", session_id,
        "--approval-mode", "default",
        "--admin-policy", policy_path,
        "--skip-trust",
        "-p", "Carry out the task given on standard input.",
    ]
    if model:
        argv += ["-m", model]
    return argv


def default_launcher(argv: List[str], *, cwd: str, env: Dict[str, str], stdin_bytes: bytes,
                     stdout_path: str, stderr_path: str):
    """Start the CLI with stdout/stderr going straight to files (raw bytes)."""
    out = open(stdout_path, "wb")
    err = open(stderr_path, "wb")
    try:
        proc = subprocess.Popen(argv, cwd=cwd, env=env, stdin=subprocess.PIPE,
                                stdout=out, stderr=err)
    finally:
        out.close()
        err.close()
    try:
        proc.stdin.write(stdin_bytes)
        proc.stdin.close()
    except (BrokenPipeError, OSError):
        pass
    return proc


def default_version_probe(config: GeminiCliConfig) -> str:
    done = subprocess.run(list(config.argv_prefix) + ["--version"], env=build_env(config),
                          capture_output=True, timeout=config.version_timeout)
    return done.stdout.decode("utf-8", "replace").strip()


