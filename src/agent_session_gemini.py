def sha256_file(path: str) -> Tuple[int, str]:
    h = hashlib.sha256()
    size = 0
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(65536), b""):
            size += len(chunk)
            h.update(chunk)
    return size, h.hexdigest()


def write_bytes(path: str, data: bytes) -> None:
    with open(path, "wb") as fh:
        fh.write(data)
        fh.flush()
        os.fsync(fh.fileno())


def tree_manifest(root: str) -> Dict[str, Any]:
    """(relative path -> kind/size/sha256) for every entry under root, without
    following symlinks. Used to prove the target tree was not modified."""
    entries: Dict[str, Any] = {}
    for dirpath, dirnames, filenames in os.walk(root, followlinks=False):
        dirnames.sort()
        rel_dir = os.path.relpath(dirpath, root)
        for name in sorted(dirnames):
            full = os.path.join(dirpath, name)
            rel = os.path.normpath(os.path.join(rel_dir, name)).replace(os.sep, "/")
            if os.path.islink(full):
                entries[rel] = {"kind": "link", "target": os.readlink(full)}
            else:
                entries[rel] = {"kind": "dir"}
        for name in sorted(filenames):
            full = os.path.join(dirpath, name)
            rel = os.path.normpath(os.path.join(rel_dir, name)).replace(os.sep, "/")
            if os.path.islink(full):
                entries[rel] = {"kind": "link", "target": os.readlink(full)}
                continue
            size, digest = sha256_file(full)
            entries[rel] = {"kind": "file", "size": size, "sha256": digest}
    return entries


def _within(child: str, parent: str) -> bool:
    child = os.path.normcase(os.path.realpath(child))
    parent = os.path.normcase(os.path.realpath(parent))
    return child == parent or child.startswith(parent.rstrip(os.sep) + os.sep)


def workspace_preflight(workspace: str, evidence_root: str, cli_home: str) -> List[str]:
    """Reasons the host restriction cannot be trusted for this workspace."""
    problems: List[str] = []
    if not isinstance(workspace, str) or not os.path.isabs(workspace):
        return ["workspace must be an absolute path"]
    if not os.path.isdir(workspace):
        return [f"workspace {workspace!r} is not a directory"]
    if _within(evidence_root, workspace) or _within(workspace, evidence_root):
        problems.append("evidence root and workspace overlap")
    if _within(cli_home, workspace) or _within(workspace, cli_home):
        problems.append("CLI home and workspace overlap")
    for entry in REFUSED_WORKSPACE_ENTRIES:
        if os.path.lexists(os.path.join(workspace, entry)):
            problems.append(f"workspace contains {entry!r} (host configuration from the target tree is not trusted)")
    current = os.path.realpath(workspace)
    while True:
        for env_file in REFUSED_ENV_FILES:
            candidate = os.path.join(current, env_file)
            if os.path.lexists(candidate):
                problems.append(f"env file {candidate!r} would be loaded by the host")
        parent = os.path.dirname(current)
        if parent == current:
            break
        current = parent
    return problems


